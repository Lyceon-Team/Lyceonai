#!/usr/bin/env node
/**
 * Generates the guardian surface's 16px type floor over the shared calendar stylesheet.
 *
 * @spec [Guardian_Closure_Plan G4-07; owner ruling R12 ("no computed font below 16px" on the
 *       guardian surface); R11 (the guardian view is the student view, read-only — reuse, do
 *       not fork)] | @implemented [2026-09-30]
 *
 * plain English: the Calendar tab renders the STUDENT's `CalendarView` (R11), whose stylesheet
 * (`client/src/features/calendar/calendar.css`, derived from the approved prototype) sets many
 * labels at 10.5–15px. The student page keeps those sizes. On a guardian page every such rule
 * is raised to 16px by a copy of its selector scoped under `.guardian-surface` (the
 * `GuardianShell` root), one class more specific than the original, inside the same @media.
 *
 * WHY GENERATED. A hand-kept list of 60-odd selectors drifts the first time the calendar
 * gains a rule. This reads calendar.css and writes the override; `--check` (run in CI) fails
 * when the committed file is not what calendar.css produces, so the floor cannot silently
 * stop covering a new rule.
 *
 * usage: node scripts/gen-guardian-type-floor.mjs [--check]
 */
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const ROOT = process.cwd();
const SOURCE = "client/src/features/calendar/calendar.css";
const TARGET = "client/src/features/guardian/guardian-type-floor.generated.css";
const FLOOR_PX = 16;
const SCOPE = ".guardian-surface";

/** The px size a declaration sets, or null. Handles `font-size` and the `font` shorthand. */
function pxOf(decl) {
  if (decl.prop === "font-size") {
    const m = /^(\d+(?:\.\d+)?)px$/.exec(decl.value.trim());
    return m ? Number(m[1]) : null;
  }
  if (decl.prop === "font") {
    const m = /(?:^|\s)(\d+(?:\.\d+)?)px(?:\/|\s)/.exec(decl.value);
    return m ? Number(m[1]) : null;
  }
  return null;
}

function scoped(selector) {
  return selector
    .split(",")
    .map((s) => `${SCOPE} ${s.trim()}`)
    .join(",\n");
}

function generate() {
  const source = fs.readFileSync(path.join(ROOT, SOURCE), "utf8");
  const root = postcss.parse(source);
  const out = postcss.root();
  let count = 0;

  root.walkRules((rule) => {
    const small = rule.nodes.some(
      (n) => n.type === "decl" && (pxOf(n) ?? FLOOR_PX) < FLOOR_PX,
    );
    if (!small) return;
    // Rebuild the enclosing at-rule chain (e.g. @media) around the override.
    let target = out;
    const chain = [];
    for (let p = rule.parent; p && p.type === "atrule"; p = p.parent)
      chain.unshift(p);
    for (const at of chain) {
      const wrapper = postcss.atRule({ name: at.name, params: at.params });
      target.append(wrapper);
      target = wrapper;
    }
    target.append(
      postcss.rule({
        selector: scoped(rule.selector),
        nodes: [postcss.decl({ prop: "font-size", value: `${FLOOR_PX}px` })],
      }),
    );
    count += 1;
  });

  const header = `/*
 * GENERATED by scripts/gen-guardian-type-floor.mjs from ${SOURCE} — do not edit.
 * Guardian_Closure_Plan G4-07 / R12: on a guardian page, every calendar rule that sets text
 * under ${FLOOR_PX}px is raised to ${FLOOR_PX}px (${count} rules). The student calendar is unchanged.
 * Regenerate: node scripts/gen-guardian-type-floor.mjs
 */
`;
  return header + out.toString() + "\n";
}

const next = generate();
const targetPath = path.join(ROOT, TARGET);
if (process.argv.includes("--check")) {
  const current = fs.existsSync(targetPath)
    ? fs.readFileSync(targetPath, "utf8")
    : "";
  if (current !== next) {
    console.error(
      `GUARDIAN TYPE FLOOR: ${TARGET} is stale. Run: node scripts/gen-guardian-type-floor.mjs`,
    );
    process.exit(1);
  }
  console.log("GUARDIAN TYPE FLOOR: up to date");
} else {
  fs.writeFileSync(targetPath, next);
  console.log(`GUARDIAN TYPE FLOOR: wrote ${TARGET}`);
}
